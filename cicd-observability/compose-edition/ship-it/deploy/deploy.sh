#!/usr/bin/env bash
# deploy.sh: ship a container image using one of four deployment strategies.
# It talks to your laptop's Docker engine (through the socket), so it works from Jenkins or from your terminal.
#
#   deploy.sh staging   IMAGE            recreate: stop the old, start the new  (a short outage)
#   deploy.sh rolling   IMAGE [N=3]      replace N replicas one by one          (no outage)
#   deploy.sh bluegreen IMAGE            start the new next to the old, then flip all traffic at once
#   deploy.sh canary    IMAGE [PCT=10]   send PCT% of traffic to the new version
#   deploy.sh promote                    canary looks good: send 100% to the new version
#   deploy.sh rollback                   canary looks bad (or the flip was a mistake): go back
#   deploy.sh status | state | clean
#
# Production traffic enters through the "chai-router" nginx container (http://localhost:8090).
set -euo pipefail

NET=shipit
ROUTER=chai-router
SLOT_PORT=8080
CHAOS_ERROR_RATE="${CHAOS_ERROR_RATE:-0}"   # set it to pretend "this release has a bug" (failure rate, 0 to 1)
CHAOS_LATENCY_MS="${CHAOS_LATENCY_MS:-0}"   # ...or "this release is slow" (extra milliseconds per order)

say()  { printf '\033[1;36m▶ %s\033[0m\n' "$*"; }
ok()   { printf '\033[1;32m✔ %s\033[0m\n' "$*"; }
die()  { printf '\033[1;31m✖ %s\033[0m\n' "$*" >&2; exit 1; }

command -v docker >/dev/null || die "docker CLI not found"
docker network inspect "$NET" >/dev/null 2>&1 || die "network '$NET' not found. Start the stack first: docker compose up -d"
docker inspect "$ROUTER" >/dev/null 2>&1 || die "container '$ROUTER' not found. Start the stack first: docker compose up -d"

start_app() {  # start_app NAME IMAGE [extra docker run args...]
  local name=$1 image=$2; shift 2
  docker run -d --name "$name" --network "$NET" --label shipit=1 --label logging=true \
    -e "CHAOS_ERROR_RATE=$CHAOS_ERROR_RATE" -e "CHAOS_LATENCY_MS=$CHAOS_LATENCY_MS" "$@" "$image" >/dev/null
}

wait_healthy() {  # wait_healthy NAME  (uses the image's HEALTHCHECK)
  local name=$1 i status
  for i in $(seq 1 60); do
    status=$(docker inspect -f '{{if .State.Health}}{{.State.Health.Status}}{{else}}none{{end}}' "$name" 2>/dev/null || echo gone)
    [ "$status" = healthy ] && return 0
    [ "$status" = gone ] && die "$name disappeared"
    sleep 1
  done
  docker logs --tail 20 "$name" >&2 || true
  die "$name did not become healthy in 60s"
}

smoke() {  # smoke NAME : deterministic checks from inside the network (ready + answers with its version)
  docker exec "$1" python -c "
import urllib.request as u
for p in ('/readyz', '/api/info'):
    assert u.urlopen('http://127.0.0.1:$SLOT_PORT' + p, timeout=3).status == 200, p
" >/dev/null 2>&1 || die "smoke test failed on $1"
}

# ---- router (nginx) -----------------------------------------------------------------------------
read_state() {  # sets STABLE OTHER WEIGHT from the comment line inside the router's config
  local line
  line=$(docker exec "$ROUTER" cat /etc/nginx/conf.d/default.conf 2>/dev/null | sed -n 's/^# state //p' || true)
  STABLE=; OTHER=; WEIGHT=0
  [ -n "$line" ] && eval "$line"
  return 0
}

write_router() {  # write_router STABLE OTHER WEIGHT
  local stable=$1 other=$2 weight=$3 f
  f=$(mktemp)
  {
    echo "# state STABLE=$stable OTHER=$other WEIGHT=$weight"
    echo "# Generated by deploy.sh. WEIGHT percent of requests go to chai-$other, the rest to chai-$stable."
    echo 'resolver 127.0.0.11 valid=2s ipv6=off;'
    echo 'split_clients "${request_id}" $slot_host {'
    if [ "$weight" -gt 0 ]; then echo "  ${weight}% chai-$other;"; fi
    echo "  *    chai-$stable;"
    echo '}'
    cat <<'CONF'
server {
  listen 80;
  # Rolling replicas share one DNS name; Docker DNS hands out every healthy one.
  location /roll/ {
    set $roll chai-roll;
    rewrite ^/roll/(.*)$ /$1 break;
    proxy_pass http://$roll:8080;
  }
  location / {
    add_header X-Slot $slot_host always;
    proxy_pass http://$slot_host:8080;
  }
}
CONF
  } > "$f"
  docker cp "$f" "$ROUTER:/etc/nginx/conf.d/default.conf"
  rm -f "$f"
  docker exec "$ROUTER" nginx -t >/dev/null 2>&1 || die "nginx rejected the generated config"
  docker exec "$ROUTER" nginx -s reload >/dev/null 2>&1
  sleep 1      # a reload is asynchronous: give the new workers a moment, so the next request already sees the new config
}

idle_slot() { [ "$1" = blue ] && echo green || echo blue; }

# ---- commands -----------------------------------------------------------------------------------
cmd=${1:-}; shift || true
case "$cmd" in
  staging)
    image=${1:?usage: deploy.sh staging IMAGE}
    say "staging: recreate (stop old, start new: expect a short outage)"
    docker rm -f chai-staging >/dev/null 2>&1 || true
    start_app chai-staging "$image" -p 8081:8080 --network-alias chai-staging
    wait_healthy chai-staging; smoke chai-staging
    ok "staging runs $image at http://localhost:8081"
    ;;

  rolling)
    image=${1:?usage: deploy.sh rolling IMAGE [N]}; n=${2:-3}
    say "rolling update to $image, $n replicas, one at a time (start new, wait healthy, retire old)"
    old=$(docker ps -q --filter label=shipit.roll=1)
    i=0
    for _ in $(seq 1 "$n"); do
      i=$((i+1)); name="chai-roll-$(date +%s)-$i"
      start_app "$name" "$image" --label shipit.roll=1 --network-alias chai-roll
      wait_healthy "$name"; smoke "$name"
      victim=$(echo "$old" | sed -n 1p); old=$(echo "$old" | sed 1d)
      if [ -n "$victim" ]; then docker stop "$victim" >/dev/null && docker rm "$victim" >/dev/null; fi
      ok "replica $i/$n now runs the new version"
    done
    for extra in $old; do docker stop "$extra" >/dev/null && docker rm "$extra" >/dev/null; done   # scaled down
    ok "rolling update finished: http://localhost:8090/roll/api/info"
    ;;

  bluegreen)
    image=${1:?usage: deploy.sh bluegreen IMAGE}
    read_state
    if [ -z "$STABLE" ]; then STABLE=blue; first=1; else first=0; fi
    new=$(idle_slot "$STABLE"); [ "$first" = 1 ] && new=blue
    say "blue/green: starting the new version in the idle slot (chai-$new), live traffic untouched"
    docker rm -f "chai-$new" >/dev/null 2>&1 || true
    start_app "chai-$new" "$image" --network-alias "chai-$new"
    wait_healthy "chai-$new"; smoke "chai-$new"
    if [ "$first" = 1 ]; then write_router blue green 0
    else say "flipping 100% of traffic to chai-$new (the old one keeps running, ready for rollback)"; write_router "$new" "$STABLE" 0; fi
    ok "production serves $image from chai-$new: http://localhost:8090"
    ;;

  canary)
    image=${1:?usage: deploy.sh canary IMAGE [PERCENT]}; pct=${2:-10}
    read_state
    [ -n "$STABLE" ] || die "nothing to compare with yet. Do a first release with: deploy.sh bluegreen IMAGE"
    new=$(idle_slot "$STABLE")
    say "canary: starting the new version as chai-$new, sending $pct% of traffic to it"
    docker rm -f "chai-$new" >/dev/null 2>&1 || true
    start_app "chai-$new" "$image" --network-alias "chai-$new"
    wait_healthy "chai-$new"; smoke "chai-$new"
    write_router "$STABLE" "$new" "$pct"
    ok "$pct% of http://localhost:8090 now goes to chai-$new. Watch it, then: deploy.sh promote   or   deploy.sh rollback"
    ;;

  promote)
    read_state; [ -n "$STABLE" ] || die "nothing deployed"
    say "promote: 100% of traffic to chai-$OTHER"
    write_router "$OTHER" "$STABLE" 0
    ok "chai-$OTHER is now the stable version (chai-$STABLE is kept for rollback)"
    ;;

  rollback)
    read_state; [ -n "$STABLE" ] || die "nothing deployed"
    if [ "$WEIGHT" -gt 0 ]; then say "rollback: canary traffic back to 0%"; write_router "$STABLE" "$OTHER" 0
    else say "rollback: switching back to chai-$OTHER"; write_router "$OTHER" "$STABLE" 0; fi
    read_state; ok "chai-$STABLE serves all traffic again"
    ;;

  state)      # machine-readable, for pipelines
    read_state; echo "STABLE=${STABLE} OTHER=${OTHER} WEIGHT=${WEIGHT}"
    ;;

  status)
    read_state
    echo "router: stable=${STABLE:-none} other=${OTHER:-none} canary-weight=${WEIGHT}%"
    docker ps --filter label=shipit=1 --format 'table {{.Names}}\t{{.Image}}\t{{.Status}}\t{{.Ports}}'
    ;;

  clean)
    docker ps -aq --filter label=shipit=1 | xargs -r docker rm -f >/dev/null
    f=$(mktemp)
    cat > "$f" <<'CONF'
resolver 127.0.0.11 valid=2s ipv6=off;
server {
  listen 80;
  default_type text/plain;
  location /roll/ { set $roll chai-roll; rewrite ^/roll/(.*)$ /$1 break; proxy_pass http://$roll:8080; }
  location / { return 503 "nothing deployed yet: run the pipeline\n"; }
}
CONF
    docker cp "$f" "$ROUTER:/etc/nginx/conf.d/default.conf"; rm -f "$f"
    docker exec "$ROUTER" nginx -s reload >/dev/null 2>&1 || true
    ok "all deployed containers removed"
    ;;

  *) sed -n '2,15p' "$0"; exit 1 ;;
esac
